import argparse
import itertools
import json
import os
import time
from urllib import request

import yaml

API_ENDPOINT = "https://release-monitoring.org/api/v2"
ITEMS_PER_PAGE = 25

XDG_CACHE_DIR = os.getenv("XDG_CACHE_HOME")
if not XDG_CACHE_DIR:
    XDG_CACHE_DIR = os.path.join(os.getenv("HOME"), ".cache")

VERSION_CACHE_FILENAME = "upstream_pkg_versions.json"
VERSION_CACHE_EXPIRE_SEC = 24 * 60 * 60
VERSION_CACHE_DIR = os.path.join(XDG_CACHE_DIR, "ptxdist")
VERSION_CACHE_FILE = os.path.join(VERSION_CACHE_DIR, VERSION_CACHE_FILENAME)


def download_pkg_version_list():
    versions = []

    for page in itertools.count(1):
        with request.urlopen(
            request.Request(
                f"{API_ENDPOINT}/packages/?distribution=PTXdist&page={page}&items_per_page={ITEMS_PER_PAGE}",
                headers={"User-Agent": "PTXdist update_check script"},
            )
        ) as url:
            data = json.load(url)
            assert data["page"] == page
            assert data["items_per_page"] == ITEMS_PER_PAGE
            total = data["total_items"]
            versions.extend(data["items"])
            print(
                f"\rDownloading current package versions ({len(versions)}/{total})",
                end="",
            )
            if len(versions) >= total:
                break
    print()
    return versions


parser = argparse.ArgumentParser(formatter_class=argparse.RawDescriptionHelpFormatter)
parser.add_argument(
    "--show-untracked",
    help="Show rules where no updated version is known",
    action="store_true",
)
parser.add_argument(
    "--show-up-to-date",
    help="Show rules which are already at the newest versions",
    action="store_true",
)
parser.add_argument(
    "report_file", help="report file generated by `ptxdist fast-bsp-report`"
)

args = parser.parse_args()

versions = None
try:
    if os.stat(VERSION_CACHE_FILE).st_mtime > time.time() - VERSION_CACHE_EXPIRE_SEC:
        print("Using cached version list")
        with open(VERSION_CACHE_FILE) as f:
            versions = json.load(f)
except FileNotFoundError:
    # No cache exists, just download it
    pass
except Exception as e:
    print(f"Unexpected error trying to read the version cache: {e}")

if not versions:
    versions = download_pkg_version_list()
    try:
        os.makedirs(VERSION_CACHE_DIR, exist_ok=True)
        with open(VERSION_CACHE_FILE, "w") as f:
            json.dump(versions, f, indent=1)
            f.write("\n")
    except Exception as e:
        print(f"Couldn't write package version cache: {e}")
print()

stable_versions = {}
for package in versions:
    stable_versions[package["name"]] = package["stable_version"]

with open(args.report_file) as f:
    report = yaml.safe_load(f)

latest_version = []
needs_update = []
untracked = []

max_pkgname_len = 0
max_version_len = 0

for pkg in report["packages"].values():
    if not "rulefile" in pkg or not "version" in pkg:
        continue

    max_pkgname_len = max(max_pkgname_len, len(pkg["name"]))
    max_version_len = max(max_version_len, len(pkg["version"]))

    version = stable_versions.get(pkg["name"])
    if version is None:
        version = stable_versions.get(pkg["name"].removeprefix("host-"))

    if version is None:
        untracked.append((pkg["name"], pkg["version"]))
    else:
        if version != pkg["version"]:
            needs_update.append((pkg["name"], pkg["version"], version))
        else:
            latest_version.append((pkg["name"], pkg["version"]))

if args.show_up_to_date:
    print("Up-to-date rules")
    print("================")
    for pkg in latest_version:
        print(f"{pkg[0].ljust(max_pkgname_len)} {pkg[1].rjust(max_version_len)}")
    print()

print("Updateable rules")
print("================")
for pkg in needs_update:
    print(
        f"{pkg[0].ljust(max_pkgname_len)} {pkg[1].rjust(max_version_len)} -> {pkg[2]}"
    )
print()

if args.show_untracked:
    print("Untracked rules")
    print("===============")
    for pkg in untracked:
        print(f"{pkg[0].ljust(max_pkgname_len)} {pkg[1].rjust(max_version_len)}")
    print()

print(
    f"Updateable: {len(needs_update)} Up-to-date: {len(latest_version)} Untracked: {len(untracked)}"
)
